using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Synthesis.Generator;

[Generator]
public sealed class SynthesisGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.AdditionalTextsProvider
            .Where(static file => Path.GetFileName(file.Path) == "model.json")
            .Select(static (file, cancellationToken) =>
                ModelParser.Parse(file.GetText(cancellationToken)!.ToString()));

        context.RegisterSourceOutput(models.Combine(context.CompilationProvider),
            static (sourceContext, input) =>
            {
                var namespaceName = input.Right.AssemblyName ?? "Generated";

                foreach (var concept in input.Left.Concepts)
                {
                    if (concept.Kind is "value_object" or "entity" or "union")
                    {
                        sourceContext.AddSource(
                            $"{concept.Name}.g.cs",
                            SourceText.From(Emitter.Emit(namespaceName, concept), Encoding.UTF8));
                    }
                }
            });
    }
}

internal static class Emitter
{
    public static string Emit(string namespaceName, Concept concept)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(namespaceName).AppendLine(";");
        source.AppendLine();

        if (concept.Kind == "union")
        {
            EmitUnion(source, concept);
            return source.ToString();
        }

        if (concept.Augments.Contains("immutable")) EmitImmutable(source, concept);
        if (concept.Augments.Contains("mutable")) EmitMutable(source, concept);
        if (concept.Augments.Contains("builder")) EmitBuilder(source, concept);

        return source.ToString();
    }

    private static void EmitImmutable(StringBuilder source, Concept concept)
    {
        source.Append("public sealed record ").Append(concept.Name).AppendLine();
        source.AppendLine("{");

        foreach (var member in Members(concept))
        {
            source.Append("    public ").Append(ImmutableType(member)).Append(' ')
                .Append(Pascal(member.Name)).AppendLine(" { get; init; }");
        }

        source.AppendLine();
        source.Append("    private ").Append(concept.Name).Append('(')
            .Append(string.Join(", ", Members(concept).Select(member => ImmutableType(member) + " " + Camel(member.Name))))
            .AppendLine(")");
        source.AppendLine("    {");
        foreach (var member in Members(concept))
        {
            source.Append("        ").Append(Pascal(member.Name)).Append(" = ").Append(Camel(member.Name)).AppendLine(";");
        }
        source.AppendLine("    }");
        source.AppendLine();
        if (concept.Augments.Contains("validation"))
        {
            EmitValidation(source, concept);
            source.AppendLine();
        }
        source.Append("    public static ").Append(concept.Name).Append(" Create(")
            .Append(string.Join(", ", Members(concept).Select(member => ImmutableType(member) + " " + Camel(member.Name))))
            .AppendLine(")");
        source.AppendLine("    {");
        if (concept.Augments.Contains("validation"))
        {
            source.Append("        var validation = Validate(")
                .Append(string.Join(", ", Members(concept).Select(member => Camel(member.Name))))
                .AppendLine(");");
            source.AppendLine("        if (!validation.IsValid) throw new global::System.ArgumentException(validation.Error);");
        }
        source.Append("        return new(")
            .Append(string.Join(", ", Members(concept).Select(member => Camel(member.Name))))
            .AppendLine(");");
        source.AppendLine("    }");

        if (concept.Augments.Contains("equality"))
        {
            source.AppendLine();
            var equalityMembers = concept.Kind == "entity"
                ? Members(concept).Where(member => member.Name == concept.IdentityField)
                : concept.Fields.Cast<Member>();
            var comparisons = string.Join(" && ", equalityMembers.Select(member =>
                $"global::System.Collections.Generic.EqualityComparer<{ImmutableType(member)}>.Default.Equals({Pascal(member.Name)}, other.{Pascal(member.Name)})"));
            source.Append("    public bool Equals(").Append(concept.Name)
                .Append("? other) => other is not null && ").Append(comparisons).AppendLine(";");
            var hashMember = equalityMembers.Single();
            source.Append("    public override int GetHashCode() => global::System.Collections.Generic.EqualityComparer<")
                .Append(ImmutableType(hashMember)).Append(">.Default.GetHashCode(")
                .Append(Pascal(hashMember.Name)).AppendLine(");");
        }

        if (concept.Augments.Contains("conversions"))
        {
            source.AppendLine();
            source.Append("    public Mutable").Append(concept.Name).AppendLine(" ToMutable() => new()");
            source.AppendLine("    {");
            foreach (var member in Members(concept))
            {
                source.Append("        ").Append(Pascal(member.Name)).Append(" = ").Append(ToMutable(member)).AppendLine(",");
            }
            source.AppendLine("    };");
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static void EmitValidation(StringBuilder source, Concept concept)
    {
        source.Append("    public static global::Synthesis.Runtime.ValidationResult Validate(")
            .Append(string.Join(", ", Members(concept).Select(member => ImmutableType(member) + " " + Camel(member.Name))))
            .AppendLine(")");
        source.AppendLine("    {");
        foreach (var field in concept.Fields)
        {
            if (field.Constraints.Contains("positive"))
            {
                source.Append("        if (").Append(Camel(field.Name)).Append(" <= 0) return global::Synthesis.Runtime.ValidationResult.Fail(\"")
                    .Append(Pascal(field.Name)).AppendLine(" must be positive.\");");
            }
            if (concept.Kind == "entity" && field.Required && field.Type != "int")
            {
                source.Append("        if (").Append(Camel(field.Name)).Append(" is null) return global::Synthesis.Runtime.ValidationResult.Fail(\"")
                    .Append(Pascal(field.Name)).AppendLine(" is required.\");");
            }
        }
        source.AppendLine("        return global::Synthesis.Runtime.ValidationResult.Ok;");
        source.AppendLine("    }");
    }

    private static void EmitUnion(StringBuilder source, Concept concept)
    {
        source.Append("public abstract record ").Append(concept.Name).AppendLine();
        source.AppendLine("{");
        source.Append("    private ").Append(concept.Name).AppendLine("() { }");
        foreach (var unionCase in concept.Cases)
        {
            source.Append("    public sealed record ").Append(unionCase.Name);
            if (unionCase.Fields.Count > 0)
            {
                source.Append('(').Append(string.Join(", ", unionCase.Fields.Select(field =>
                    ImmutableType(field) + " " + Pascal(field.Name)))).Append(')');
            }
            source.Append(" : ").Append(concept.Name).AppendLine(";");
        }
        source.AppendLine();
        source.Append("    public T Match<T>(")
            .Append(string.Join(", ", concept.Cases.Select(unionCase =>
                $"global::System.Func<{unionCase.Name}, T> on{unionCase.Name}")))
            .AppendLine(") => this switch");
        source.AppendLine("    {");
        foreach (var unionCase in concept.Cases)
        {
            source.Append("        ").Append(unionCase.Name).Append(" value => on")
                .Append(unionCase.Name).AppendLine("(value),");
        }
        source.AppendLine("        _ => throw new global::System.InvalidOperationException(),");
        source.AppendLine("    };");
        source.AppendLine("}");
    }

    private static void EmitMutable(StringBuilder source, Concept concept)
    {
        source.Append("public sealed class Mutable").Append(concept.Name).AppendLine();
        source.AppendLine("{");
        foreach (var member in Members(concept))
        {
            source.Append("    public ").Append(MutableType(member)).Append(' ')
                .Append(Pascal(member.Name)).Append(" { get; set; } = ").Append(MutableDefault(member)).AppendLine(";");
        }

        if (concept.Augments.Contains("conversions"))
        {
            source.AppendLine();
            source.Append("    public ").Append(concept.Name).Append(" ToImmutable() => ").Append(concept.Name).Append(".Create(")
                .Append(string.Join(", ", Members(concept).Select(ToImmutable))).AppendLine(");");
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static void EmitBuilder(StringBuilder source, Concept concept)
    {
        source.Append("public sealed class ").Append(concept.Name).AppendLine("Builder");
        source.AppendLine("{");
        foreach (var field in concept.Fields)
        {
            source.Append("    private ").Append(ImmutableType(field)).Append(" _")
                .Append(Camel(field.Name)).Append(" = ").Append(FieldDefault(field)).AppendLine(";");
        }
        foreach (var owned in concept.Owns)
        {
            source.Append("    private readonly global::System.Collections.Generic.List<")
                .Append(owned.Type).Append("> _").Append(Camel(owned.Name)).AppendLine(" = new();");
        }

        foreach (var field in concept.Fields)
        {
            source.AppendLine();
            source.Append("    public ").Append(concept.Name).Append("Builder With").Append(Pascal(field.Name))
                .Append('(').Append(ImmutableType(field)).Append(' ').Append(Camel(field.Name)).AppendLine(")");
            source.AppendLine("    {");
            source.Append("        _").Append(Camel(field.Name)).Append(" = ").Append(Camel(field.Name)).AppendLine(";");
            source.AppendLine("        return this;");
            source.AppendLine("    }");
        }
        foreach (var owned in concept.Owns)
        {
            source.AppendLine();
            source.Append("    public ").Append(concept.Name).Append("Builder Add").Append(Singular(Pascal(owned.Name)))
                .Append('(').Append(owned.Type).Append(' ').Append(Camel(Singular(owned.Name))).AppendLine(")");
            source.AppendLine("    {");
            source.Append("        _").Append(Camel(owned.Name)).Append(".Add(").Append(Camel(Singular(owned.Name))).AppendLine(");");
            source.AppendLine("        return this;");
            source.AppendLine("    }");
        }

        source.AppendLine();
        source.Append("    public ").Append(concept.Name).Append(" Build() => ").Append(concept.Name).Append(".Create(")
            .Append(string.Join(", ", Members(concept).Select(member => "_" + Camel(member.Name)))).AppendLine(");");
        source.AppendLine("}");
    }

    private static IEnumerable<Member> Members(Concept concept) => concept.Fields.Concat(concept.Owns);
    private static string ImmutableType(Member member) => member.IsMany
        ? $"global::System.Collections.Generic.IReadOnlyList<{member.Type}>"
        : TypeName(member.Type);
    private static string MutableType(Member member) => member.IsMany
        ? $"global::System.Collections.Generic.List<Mutable{member.Type}>"
        : IsConcept(member.Type) ? "Mutable" + member.Type : TypeName(member.Type);
    private static string TypeName(string type) => type switch { "int" => "int", "string" => "string", _ => type };
    private static bool IsConcept(string type) => type is not "int" and not "string";
    private static string FieldDefault(Member member) => member.Type == "int" ? "default" : "null!";
    private static string MutableDefault(Member member) => member.IsMany ? "new()" : FieldDefault(member);
    private static string ToMutable(Member member) => member.IsMany
        ? $"global::System.Linq.Enumerable.ToList(global::System.Linq.Enumerable.Select({Pascal(member.Name)}, item => item.ToMutable()))"
        : IsConcept(member.Type) ? Pascal(member.Name) + ".ToMutable()" : Pascal(member.Name);
    private static string ToImmutable(Member member) => member.IsMany
        ? $"global::System.Linq.Enumerable.ToList(global::System.Linq.Enumerable.Select({Pascal(member.Name)}, item => item.ToImmutable()))"
        : IsConcept(member.Type) ? Pascal(member.Name) + ".ToImmutable()" : Pascal(member.Name);
    private static string Pascal(string value) => string.Concat(value.Split('_').Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
    private static string Camel(string value)
    {
        var pascal = Pascal(value);
        return char.ToLowerInvariant(pascal[0]) + pascal.Substring(1);
    }
    private static string Singular(string value) => value.EndsWith("s", StringComparison.Ordinal)
        ? value.Substring(0, value.Length - 1)
        : value;
}

internal sealed class Model
{
    public List<Concept> Concepts { get; } = new();
}

internal sealed class Concept
{
    public string Name { get; set; } = "";
    public string Kind { get; set; } = "";
    public string IdentityField { get; set; } = "";
    public List<Member> Fields { get; } = new();
    public List<Member> Owns { get; } = new();
    public List<UnionCase> Cases { get; } = new();
    public HashSet<string> Augments { get; } = new(StringComparer.Ordinal);
}

internal sealed class UnionCase
{
    public string Name { get; set; } = "";
    public List<Member> Fields { get; } = new();
}

internal sealed class Member
{
    public string Name { get; set; } = "";
    public string Type { get; set; } = "";
    public bool IsMany { get; set; }
    public bool Required { get; set; }
    public HashSet<string> Constraints { get; } = new(StringComparer.Ordinal);
}

internal static class ModelParser
{
    public static Model Parse(string json)
    {
        var root = JsonParser.Parse(json).Object;
        var model = new Model();
        foreach (var conceptPair in root["concepts"].Object)
        {
            var value = conceptPair.Value.Object;
            var concept = new Concept
            {
                Name = conceptPair.Key,
                Kind = value["kind"].String,
                IdentityField = value.TryGetValue("identity_field", out var identity) ? identity.String : "",
            };

            if (value.TryGetValue("fields", out var fields))
            {
                foreach (var field in fields.Object)
                {
                    concept.Fields.Add(ParseField(field.Key, field.Value));
                }
            }
            if (value.TryGetValue("owns", out var owns))
            {
                foreach (var owned in owns.Object)
                {
                    concept.Owns.Add(new Member
                    {
                        Name = owned.Key,
                        Type = owned.Value.Object["concept"].String,
                        IsMany = owned.Value.Object["multiplicity"].String == "many",
                    });
                }
            }
            if (value.TryGetValue("cases", out var cases))
            {
                foreach (var caseValue in cases.Array)
                {
                    var unionCase = new UnionCase { Name = caseValue.Object["name"].String };
                    foreach (var field in caseValue.Object["fields"].Object)
                    {
                        unionCase.Fields.Add(ParseField(field.Key, field.Value));
                    }
                    concept.Cases.Add(unionCase);
                }
            }
            foreach (var augment in value["augments"].Array) concept.Augments.Add(augment.String);
            model.Concepts.Add(concept);
        }
        return model;
    }

    private static Member ParseField(string name, JsonValue value)
    {
        var member = new Member
        {
            Name = name,
            Type = value.Object["type"].String,
            Required = value.Object.ContainsKey("required"),
        };
        if (value.Object.TryGetValue("constraints", out var constraints))
        {
            foreach (var constraint in constraints.Array) member.Constraints.Add(constraint.String);
        }
        return member;
    }
}

internal sealed class JsonValue
{
    public Dictionary<string, JsonValue> Object { get; set; } = new(StringComparer.Ordinal);
    public List<JsonValue> Array { get; set; } = new();
    public string String { get; set; } = "";
}

internal sealed class JsonParser
{
    private readonly string text;
    private int position;

    private JsonParser(string text) => this.text = text;
    public static JsonValue Parse(string text) => new JsonParser(text).ReadValue();

    private JsonValue ReadValue()
    {
        SkipWhitespace();
        return text[position] switch
        {
            '{' => ReadObject(),
            '[' => ReadArray(),
            '"' => new JsonValue { String = ReadString() },
            _ => ReadLiteral(),
        };
    }

    private JsonValue ReadObject()
    {
        var value = new JsonValue();
        position++;
        SkipWhitespace();
        while (text[position] != '}')
        {
            var key = ReadString();
            SkipWhitespace();
            position++;
            value.Object.Add(key, ReadValue());
            SkipWhitespace();
            if (text[position] == ',') { position++; SkipWhitespace(); }
        }
        position++;
        return value;
    }

    private JsonValue ReadArray()
    {
        var value = new JsonValue();
        position++;
        SkipWhitespace();
        while (text[position] != ']')
        {
            value.Array.Add(ReadValue());
            SkipWhitespace();
            if (text[position] == ',') { position++; SkipWhitespace(); }
        }
        position++;
        return value;
    }

    private string ReadString()
    {
        var result = new StringBuilder();
        position++;
        while (text[position] != '"')
        {
            var character = text[position++];
            if (character == '\\')
            {
                character = text[position++] switch { 'n' => '\n', 'r' => '\r', 't' => '\t', var escaped => escaped };
            }
            result.Append(character);
        }
        position++;
        return result.ToString();
    }

    private JsonValue ReadLiteral()
    {
        while (position < text.Length && text[position] is not ',' and not '}' and not ']') position++;
        return new JsonValue();
    }

    private void SkipWhitespace()
    {
        while (position < text.Length && char.IsWhiteSpace(text[position])) position++;
    }
}
